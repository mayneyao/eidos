import { marked, type MarkedToken } from "marked"
import { isMap, isScalar, parseDocument } from "yaml"

export function canSummarizeFile(name: string): boolean {
  return explorerSummaryKind(name) !== null
}

export function explorerSummaryKind(
  name: string
): "markdown" | "json" | "text" | "eidos" | null {
  if (/\.eidos$/i.test(name)) return "eidos"
  if (/\.(md|markdown)$/i.test(name)) return "markdown"
  if (/\.json$/i.test(name)) return "json"
  if (
    /\.(txt|text|log|csv|tsv|jsonl|ndjson|yaml|yml|toml|ini|conf|xml|html?|css|[cm]?js|jsx|tsx?|sql|sh|py|rs|swift|kt|java|[ch]|cpp|go)$/i.test(
      name
    )
  )
    return "text"
  return null
}

function plainExcerpt(content: string): string {
  const text = content
    .slice(0, 16_384)
    .replace(/^\uFEFF/, "")
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, 240)
  return text.replace(/[\u200b-\u200d\u2060\ufeff]/g, "").trim() ? text : ""
}

function inlineTitle(tokens: readonly MarkedToken[]): string {
  return tokens
    .map((token) => {
      if (token.type === "html") return ""
      if (token.type === "br") return " "
      if ("tokens" in token && token.tokens) return inlineTitle(token.tokens)
      return token.text ?? ""
    })
    .join("")
}

/** A bounded document title; never take headings from code, quotes or HTML comments. */
export function markdownDocumentTitle(content: string): string | undefined {
  let body = content
    .slice(0, 16_384)
    .replace(/^\uFEFF/, "")
    .replace(/\r\n?/g, "\n")
  const header = /^---[\t ]*\n([\s\S]*?)\n(?:---|\.\.\.)[\t ]*(?:\n|$)/.exec(
    body
  )
  if (header) {
    body = body.slice(header[0].length)
    const document = parseDocument(header[1], {
      strict: true,
      uniqueKeys: true,
    })
    if (!document.errors.length && isMap(document.contents)) {
      const title = document.get("title", true)
      if (isScalar(title) && typeof title.value === "string") {
        const text = plainExcerpt(title.value)
        if (text) return text
      }
    }
  }
  const heading = marked
    .lexer(body)
    .find((token) => token.type === "heading" && token.depth === 1)
  return heading?.type === "heading"
    ? plainExcerpt(inlineTitle(heading.tokens ?? [])) || undefined
    : undefined
}

export function summarizeFileContent(name: string, content: string): string {
  const kind = explorerSummaryKind(name)
  if (kind === "markdown") return summarizeDocument(content)
  if (kind !== "json") return plainExcerpt(content)
  if (content.length > 256 * 1024) return plainExcerpt(content)
  try {
    const value: unknown = JSON.parse(content.replace(/^\uFEFF/, ""))
    const scalar = (item: unknown): string => {
      if (item === null) return "null"
      if (typeof item === "object")
        return Array.isArray(item) ? `[…${item.length}]` : "{…}"
      return String(item)
    }
    const item = Array.isArray(value) ? value[0] : value
    if (
      item === undefined ||
      (item && typeof item === "object" && !Object.keys(item).length)
    )
      return ""
    return plainExcerpt(
      item && typeof item === "object" && !Array.isArray(item)
        ? Object.entries(item)
            .slice(0, 6)
            .map(([key, value]) => `${key}: ${scalar(value)}`)
            .join(" · ")
        : Array.isArray(value)
          ? value.slice(0, 8).map(scalar).join(" · ")
          : scalar(value)
    )
  } catch {
    return plainExcerpt(content)
  }
}
/** A short plain-text excerpt, never interpreted as HTML or generated by AI. */
export function summarizeDocument(content: string): string {
  const text = content
    .slice(0, 16_384)
    .replace(/^\uFEFF/, "")
    .replace(/^---[\t ]*\r?\n[\s\S]*?\r?\n(?:---|\.\.\.)[\t ]*(?:\r?\n|$)/, "")
    .replace(/^```[^\n]*\n[\s\S]*?^```[^\n]*$/gm, "")
    .replace(/!\[[^\]]*\]\([^)]*\)/g, "")
    .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")
    .replace(/^ {0,3}#{1,6}(?:[\t ]+.*)?$/gm, "")
    .replace(/^ {0,3}\S[^\n]*\r?\n {0,3}(?:=+|-+)[\t ]*$/gm, "")
    .replace(
      /^ {0,3}(?:(?:-[\t ]*){3,}|(?:\*[\t ]*){3,}|(?:_[\t ]*){3,})$/gm,
      ""
    )
    .replace(/<[^>]*>/g, "")
    .replace(/^\s*(?:>\s*|[-*+]\s+|\d+\.\s+)/gm, "")
    .replace(/[*_`~]/g, "")
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, 240)
  return text.replace(/[\u200b-\u200d\u2060\ufeff]/g, "").trim() ? text : ""
}
