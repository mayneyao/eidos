import ts from "typescript"
import { mkdir, readFile, writeFile } from "node:fs/promises"
import { fileURLToPath } from "node:url"
import { pages } from "./plugin-api-pages.mjs"
import { notes } from "./plugin-api-notes.mjs"

const root = new URL("../../../", import.meta.url)
const sdkPath = "packages/plugin-sdk/src/index.ts"
const errorPath = "packages/plugin-runtime/src/errors.ts"
const parse = async (path) =>
  ts.createSourceFile(
    path,
    await readFile(new URL(path, root), "utf8"),
    ts.ScriptTarget.Latest,
    true
  )
const sdk = await parse(sdkPath)
const errors = await parse(errorPath)
const declarations = sdk.statements.filter(
  (node) =>
    (ts.isInterfaceDeclaration(node) || ts.isTypeAliasDeclaration(node)) &&
    node.modifiers?.some(
      (modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword
    )
)
const memberNames = new Set(
  declarations.flatMap((node) =>
    ts.isInterfaceDeclaration(node)
      ? node.members.map(
          (member) => `${node.name.text}.${member.name?.getText(sdk)}`
        )
      : []
  )
)
for (const key of Object.keys(notes))
  if (!memberNames.has(key)) throw new Error(`Stale API behavior note: ${key}`)
const names = new Set(declarations.map((node) => node.name.text))
const assigned = new Map()
for (const [slug, , , types] of pages) {
  for (const name of types) {
    if (!names.has(name) || assigned.has(name))
      throw new Error(`Invalid or duplicate API mapping: ${name}`)
    assigned.set(name, slug)
  }
}
for (const name of names) if (!assigned.has(name)) assigned.set(name, "types")
const errorCode = errors.statements.find(
  (node) =>
    ts.isTypeAliasDeclaration(node) && node.name.text === "PluginErrorCode"
)
if (!errorCode) throw new Error("Missing runtime error contract")
assigned.set("PluginErrorCode", "types")
const printer = ts.createPrinter({ removeComments: true })
const print = (node, source = sdk) =>
  printer.printNode(ts.EmitHint.Unspecified, node, source).trim()
const anchor = (name) => name.toLowerCase()
const code = (value) => `\n\n\`\`\`ts\n${value}\n\`\`\`\n\n`
const inline = (value) =>
  `\`${value.replaceAll("|", "&#124;").replaceAll("\n", " ")}\``
const check = process.argv.includes("--check")
const failures = []

for (const locale of ["en", "zh-cn"]) {
  const zh = locale === "zh-cn"
  const base = `${zh ? "/zh-cn" : ""}/plugins/`
  for (const [slug, en, cn, , guide, description, translation] of pages) {
    const title = zh ? cn : en
    let text = `---\ntitle: ${JSON.stringify(title)}\ndescription: ${JSON.stringify(zh ? `${title} 的 SDK 签名、权限和行为约定。` : `SDK signatures, permissions and behavior for ${title}.`)}\n---\n\n{/* Generated by scripts/sync-plugin-api.mjs. Edit SDK types or scripts/plugin-api-pages.mjs. */}\n\n${zh ? translation : description}\n\n${zh ? "使用指南" : "Usage guide"}: [${guide}](${base}${guide}/). [${zh ? "API 索引" : "API index"}](${base}api/).\n\n${zh ? "签名、参数及返回类型从 SDK 自动生成；可选成员不保证在每个宿主和上下文中存在。" : "Signatures, parameters and return types are generated from the SDK. Optional members are not available in every host and context."}\n`
    const nodes = declarations.filter(
      (node) => assigned.get(node.name.text) === slug
    )
    if (slug === "types") nodes.push(errorCode)
    for (const node of nodes) {
      const source = node === errorCode ? errors : sdk
      const name = node.name.text
      const line =
        source.getLineAndCharacterOfPosition(node.getStart(source)).line + 1
      const sourcePath = node === errorCode ? errorPath : sdkPath
      text += `\n## ${name}\n\n[${zh ? "源码" : "Source"}](https://github.com/mayneyao/eidos/blob/dev/${sourcePath}#L${line})\n`
      if (ts.isInterfaceDeclaration(node)) {
        const heritage =
          node.heritageClauses?.map((clause) => print(clause)).join(" ") ?? ""
        if (heritage)
          text += code(`interface ${name} ${heritage} { /* members below */ }`)
        for (const member of node.members) {
          const memberName = member.name?.getText(source) ?? "signature"
          const note = notes[`${name}.${memberName}`]?.[zh ? 1 : 0]
          text += `\n### ${name}.${memberName}\n${note ? `\n${note}\n` : ""}${code(print(member, source))}`
          if (ts.isMethodSignature(member)) {
            if (member.parameters.length) {
              text += `| ${zh ? "参数" : "Parameter"} | ${zh ? "类型" : "Type"} | ${zh ? "必填" : "Required"} |\n| --- | --- | --- |\n`
              for (const parameter of member.parameters)
                text += `| ${inline(parameter.name.getText(source))} | ${inline(print(parameter.type, source))} | ${parameter.questionToken ? (zh ? "否" : "No") : zh ? "是" : "Yes"} |\n`
            }
            text += `\n${zh ? "返回值" : "Returns"}: ${inline(print(member.type, source))}.\n`
          }
        }
      } else text += code(print(node, source))
      const refs = new Set()
      const visit = (child) => {
        if (ts.isTypeReferenceNode(child) && ts.isIdentifier(child.typeName)) {
          const ref = child.typeName.text
          if (assigned.has(ref) && ref !== name) refs.add(ref)
        }
        ts.forEachChild(child, visit)
      }
      visit(node)
      // Interface inheritance uses ExpressionWithTypeArguments instead of TypeReference.
      for (const clause of node.heritageClauses ?? [])
        for (const type of clause.types) {
          const ref = type.expression.getText(source)
          if (assigned.has(ref)) refs.add(ref)
        }
      if (refs.size)
        text += `\n${zh ? "关联类型" : "Related types"}: ${[...refs].map((ref) => `[${ref}](${base}api/${assigned.get(ref)}/#${anchor(ref)})`).join(", ")}.\n`
    }
    text = `${text.trimEnd()}\n`
    const destination = new URL(
      `apps/docs/src/content/docs/${zh ? "zh-cn/" : ""}plugins/api/${slug}.mdx`,
      root
    )
    if (check) {
      const actual = await readFile(destination, "utf8").catch(() => "")
      if (actual !== text) failures.push(fileURLToPath(destination))
    } else {
      await mkdir(new URL("./", destination), { recursive: true })
      await writeFile(destination, text)
    }
  }
}
if (failures.length)
  throw new Error(
    `Stale plugin API reference. Run pnpm --filter docs sync:plugin-api:\n${failures.join("\n")}`
  )
console.log(
  `Plugin API ${check ? "checked" : "generated"}: ${names.size} SDK declarations, ${pages.length * 2} bilingual pages.`
)
