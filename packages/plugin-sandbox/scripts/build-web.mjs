import { build } from "esbuild"
import { fileURLToPath } from "node:url"
import { readFile, writeFile } from "node:fs/promises"
import { createRequire } from "node:module"
import path from "node:path"
const root = new URL("../", import.meta.url)
const check = process.argv.includes("--check")
const emit = async (name, text) => {
  const target = new URL(`../../crates/eidos-plugin-sandbox/src/${name}`, root)
  if (check) {
    if ((await readFile(target, "utf8")) !== text)
      throw new Error(
        `Stale ${name}; run pnpm --filter @eidos.space/plugin-sandbox build:web`
      )
  } else await writeFile(target, text)
}
for (const [name, source] of [
  [
    "streams",
    'import * as streams from "web-streams-polyfill"; Object.assign(globalThis, streams);',
  ],
  [
    "url",
    'import { URL, URLSearchParams } from "whatwg-url"; Object.assign(globalThis, { URL, URLSearchParams });',
  ],
]) {
  const result = await build({
    stdin: { contents: source, resolveDir: fileURLToPath(root) },
    bundle: true,
    platform: "browser",
    format: "iife",
    target: "es2022",
    minify: true,
    legalComments: "inline",
    write: false,
  })
  await emit(`generated-${name}.js`, result.outputFiles[0].text)
}
let notices = "Bundled Web platform dependencies (generated by build-web.mjs)\n"
const require = createRequire(new URL("package.json", root))
const urlRequire = createRequire(require.resolve("whatwg-url"))
const tr46Require = createRequire(urlRequire.resolve("tr46"))
for (const [name, resolver, license] of [
  ["web-streams-polyfill", require, "LICENSE"],
  ["whatwg-url", require, "LICENSE.txt"],
  ["webidl-conversions", urlRequire, "LICENSE.md"],
  ["tr46", urlRequire, "LICENSE.md"],
  ["punycode/", tr46Require, "LICENSE-MIT.txt"],
]) {
  let directory = path.dirname(resolver.resolve(name))
  while (true) {
    try {
      notices += `\n--- ${name} ---\n${await readFile(path.join(directory, license), "utf8")}\n`
      break
    } catch (error) {
      if (directory === path.dirname(directory)) throw error
      directory = path.dirname(directory)
    }
  }
}
await emit("generated-web-NOTICE.txt", notices)
