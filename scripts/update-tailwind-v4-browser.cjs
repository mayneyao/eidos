#!/usr/bin/env node

/**
 * Update Tailwind CSS browser build to v4 for extension environment
 * 
 * This script downloads the @tailwindcss/browser package and updates
 * the tailwind-raw.js file used in the extension sandbox environment.
 * 
 * Usage:
 *   node scripts/update-tailwind-v4-browser.cjs
 * 
 * Tailwind v4 changes:
 * - Uses @tailwindcss/browser instead of the old CDN build
 * - Configuration via CSS @theme instead of tailwind.config.js
 * - No @apply support in browser build
 */

const fs = require('fs')
const path = require('path')
const https = require('https')

const CDN_URL = 'https://cdn.jsdelivr.net/npm/@tailwindcss/browser@4/dist/index.global.js'

// Files to update
const TARGETS = [
  {
    rawPath: path.join(__dirname, '../apps/web-app/components/block-renderer/tailwind-raw.js'),
    configPath: path.join(__dirname, '../apps/web-app/components/block-renderer/tailwind-config.ts'),
    themeCssPath: path.join(__dirname, '../apps/web-app/components/block-renderer/tailwind-v4-theme.css'),
  },
  {
    rawPath: path.join(__dirname, '../packages/ext-server/src/js/tailwind-raw.js'),
    generatedPath: path.join(__dirname, '../packages/ext-server/src/generated/tailwindRawJs.ts'),
    themeCssPath: path.join(__dirname, '../packages/ext-server/src/js/tailwind-v4-theme.css'),
  }
]

function downloadFile(url, dest) {
  return new Promise((resolve, reject) => {
    console.log(`Downloading from ${url}...`)
    
    const file = fs.createWriteStream(dest)
    https.get(url, (response) => {
      if (response.statusCode === 302 || response.statusCode === 301) {
        file.close()
        fs.unlinkSync(dest)
        downloadFile(response.headers.location, dest).then(resolve).catch(reject)
        return
      }
      
      if (response.statusCode !== 200) {
        reject(new Error(`Failed to download: ${response.statusCode}`))
        return
      }
      
      response.pipe(file)
      file.on('finish', () => {
        file.close()
        resolve()
      })
    }).on('error', (err) => {
      fs.unlinkSync(dest)
      reject(err)
    })
  })
}

function generateWrappedCode(tailwindCode, themeCssCode) {
  // Remove @import "tailwindcss"; since tailwind browser build already includes it
  const themeWithoutImport = themeCssCode.replace(/@import\s+["']tailwindcss["'];?\n?/g, '')
  
  return `// Tailwind CSS v4 Browser Build
// Downloaded from: ${CDN_URL}
// This file is auto-generated by scripts/update-tailwind-v4-browser.cjs
// Do not edit manually

${tailwindCode}

// Inject theme configuration for Eidos extensions
(function() {
  if (typeof document !== 'undefined') {
    const styleEl = document.createElement('style')
    styleEl.type = 'text/tailwindcss'
    styleEl.textContent = \`${themeWithoutImport.replace(/`/g, '\\`')}\`
    document.head.appendChild(styleEl)
  }
})()
`
}

function generateTsModule(tailwindCode, themeCssCode) {
  const wrapped = generateWrappedCode(tailwindCode, themeCssCode)
  return `// Auto-generated from src/js/tailwind-raw.js
// This file is auto-generated by scripts/update-tailwind-v4-browser.cjs
// Do not edit manually

export const tailwindRawJs = ${JSON.stringify(wrapped)}
`
}

async function updateTarget(target, tailwindCode) {
  const { rawPath, generatedPath, configPath, themeCssPath } = target
  
  // Read theme CSS
  if (!fs.existsSync(themeCssPath)) {
    throw new Error(`Theme CSS file not found: ${themeCssPath}`)
  }
  const themeCssCode = fs.readFileSync(themeCssPath, 'utf-8')
  
  // Backup old file
  if (fs.existsSync(rawPath)) {
    const backupPath = rawPath + '.v3.backup'
    fs.copyFileSync(rawPath, backupPath)
    console.log(`  Backed up: ${path.relative(process.cwd(), backupPath)}`)
  }
  
  // Write new raw file
  const wrappedCode = generateWrappedCode(tailwindCode, themeCssCode)
  fs.writeFileSync(rawPath, wrappedCode)
  console.log(`  Updated: ${path.relative(process.cwd(), rawPath)}`)
  
  // Generate TypeScript module if needed
  if (generatedPath) {
    const tsCode = generateTsModule(tailwindCode, themeCssCode)
    fs.writeFileSync(generatedPath, tsCode)
    console.log(`  Generated: ${path.relative(process.cwd(), generatedPath)}`)
  }
  
  // Warn about config file
  if (configPath && fs.existsSync(configPath)) {
    console.log(`  ⚠️  ${path.relative(process.cwd(), configPath)} is deprecated in v4`)
    console.log(`     Tailwind v4 browser build uses CSS-based configuration (@theme)`)
    console.log(`     Theme config is now in: ${path.relative(process.cwd(), themeCssPath)}`)
  }
  
  // Calculate sizes
  const oldSize = fs.existsSync(rawPath + '.v3.backup')
    ? (fs.statSync(rawPath + '.v3.backup').size / 1024).toFixed(2)
    : 'N/A'
  const newSize = (fs.statSync(rawPath).size / 1024).toFixed(2)
  console.log(`  Size: ${oldSize} KB -> ${newSize} KB`)
}

async function main() {
  console.log('Updating Tailwind CSS to v4 for extension environment...\n')
  
  try {
    // Create temporary directory
    const tmpDir = path.join(__dirname, '../tmp')
    if (!fs.existsSync(tmpDir)) {
      fs.mkdirSync(tmpDir, { recursive: true })
    }
    
    const downloadedPath = path.join(tmpDir, 'tailwind.v4.js')
    
    // Download Tailwind v4 browser build
    await downloadFile(CDN_URL, downloadedPath)
    console.log('')
    
    // Read the downloaded file
    const tailwindCode = fs.readFileSync(downloadedPath, 'utf-8')
    
    // Update all targets
    for (const target of TARGETS) {
      console.log(`Updating ${path.relative(process.cwd(), target.rawPath)}...`)
      await updateTarget(target, tailwindCode)
      console.log('')
    }
    
    // Clean up
    fs.unlinkSync(downloadedPath)
    
    console.log('✅ Tailwind CSS v4 browser build updated successfully!\n')
    
    console.log('Important changes in v4:')
    console.log('  • CSS-first configuration via @theme (not tailwind.config.js)')
    console.log('  • @apply directive not supported in browser build')
    console.log('  • Theme variables are auto-injected for extensions')
    console.log('  • ~70% smaller bundle size\n')
    
    console.log('Theme configuration:')
    console.log('  • apps/web-app/components/block-renderer/tailwind-v4-theme.css')
    console.log('  • packages/ext-server/src/js/tailwind-v4-theme.css')
    
  } catch (error) {
    console.error('\n❌ Error:', error.message)
    process.exit(1)
  }
}

main()
